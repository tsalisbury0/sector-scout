#!/usr/bin/env python3
"""Regenerate the band tables from the 3GPP data in `tool/banddata`.

Two consumers read the same numbers: the phone app (through
`lib/models/band_tables.dart`, generated by this script) and the desktop test
source (through `bands.json`, which it loads at startup). Keeping one source of
truth is the whole point — a band the desktop can dial has to be one the phone
can decode, or the source would be able to serve a carrier the app cannot read.

The data comes from https://github.com/hoon/arfcn (MIT), which transcribes:

  * `EutraBands.ts` — 3GPP TS 36.101 Table 5.7.3-1: every LTE band's downlink
    and uplink EARFCN ranges with their lowest frequencies.
  * `NrBands.ts` — 3GPP TS 38.104 Table 5.2-1/2: every NR band's uplink and
    downlink frequency ranges and duplex mode.

Run from the repository root:

    python tool/gen_bands.py

It rewrites `bands.json` and `lib/models/band_tables.dart`.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tool" / "banddata"
LTE_SOURCE = DATA / "EutraBands.ts"
NR_SOURCE = DATA / "NrBands.ts"
JSON_OUT = ROOT / "bands.json"
DART_OUT = ROOT / "lib" / "models" / "band_tables.dart"

BLOCK = re.compile(r"\{([^{}]*)\}", re.S)
FIELD = re.compile(r"(\w+):\s*(null|'[^']*'|[-0-9.]+)")


def _rows(path: Path) -> list[dict[str, object]]:
    """Every `{ band: ..., ... }` object in a table file."""
    rows: list[dict[str, object]] = []
    for block in BLOCK.findall(path.read_text(encoding="utf-8")):
        row: dict[str, object] = {}
        for key, raw in FIELD.findall(block):
            if raw == "null":
                row[key] = None
            elif raw.startswith("'"):
                row[key] = raw.strip("'")
            else:
                number = float(raw)
                row[key] = int(number) if number.is_integer() else number
        if "band" in row:
            rows.append(row)
    return rows


def nr_nref(mhz: float) -> int:
    """NR-ARFCN for a frequency, on the global raster (TS 38.104 5.4.2.1)."""
    if mhz < 3000:
        return round(mhz / 0.005)
    if mhz < 24250.08:
        return round(600000 + (mhz - 3000) / 0.015)
    return round(2016667 + (mhz - 24250.08) / 0.06)


def lte_bands() -> list[dict[str, object]]:
    out: list[dict[str, object]] = []
    for row in _rows(LTE_SOURCE):
        band = row["band"]
        first, last = row.get("n_dl_lo"), row.get("n_dl_hi")
        dl_low = row.get("f_dl_lo")
        if band is None or first is None or last is None or dl_low is None:
            continue
        ul_low = row.get("f_ul_lo")
        ul_high = row.get("f_ul_hi")
        mode = str(row.get("duplex_mode") or "FDD")
        if mode == "TDD":
            ul_low, ul_high = dl_low, row.get("f_dl_hi")
        elif ul_low is None:
            mode = "SDL"
        out.append(
            {
                "band": int(band),
                "first": int(first),
                "last": int(last),
                "dlLow": float(dl_low),
                "ulLow": None if ul_low is None else float(ul_low),
                "ulHigh": None if ul_high is None else float(ul_high),
                "mode": mode,
            }
        )
    return sorted(out, key=lambda entry: entry["band"])


def nr_bands() -> list[dict[str, object]]:
    out: list[dict[str, object]] = []
    for row in _rows(NR_SOURCE):
        band = row["band"]
        dl_lo, dl_hi = row.get("f_dl_lo"), row.get("f_dl_hi")
        ul_lo = row.get("f_ul_lo")
        ul_hi = row.get("f_ul_hi")
        mode = str(row.get("duplex_mode") or "FDD")
        # Supplementary uplink bands have no downlink at all: no phone can serve
        # one as a cell, so there is no ARFCN window to publish.
        if band is None or dl_lo is None or dl_hi is None:
            continue
        if mode == "TDD":
            ul_lo, ul_hi = dl_lo, dl_hi
        elif ul_lo is None:
            mode = "SDL"
        out.append(
            {
                "band": int(band),
                "first": nr_nref(float(dl_lo)),
                "last": nr_nref(float(dl_hi)),
                "dlLow": float(dl_lo),
                "ulLow": None if ul_lo is None else float(ul_lo),
                "ulHigh": None if ul_hi is None else float(ul_hi),
                "mode": mode,
            }
        )
    return sorted(out, key=lambda entry: entry["band"])


def main() -> int:
    lte = lte_bands()
    nr = nr_bands()
    payload = {
        "source": {
            "lte": "3GPP TS 36.101 Table 5.7.3-1",
            "nr": "3GPP TS 38.104 Table 5.2-1/2",
            "via": "https://github.com/hoon/arfcn (MIT)",
        },
        "lte": lte,
        "nr": nr,
    }
    JSON_OUT.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")

    def dart_map(name: str, rows: list[dict[str, object]], doc: str) -> str:
        lines = [f"/// {doc}", f"const Map<int, BandPlan> {name} = {{"]
        for row in rows:
            ul = "null" if row["ulLow"] is None else f'{row["ulLow"]:g}'
            hi = "null" if row["ulHigh"] is None else f'{row["ulHigh"]:g}'
            lines.append(
                f'  {row["band"]}: BandPlan({row["first"]}, {row["last"]}, '
                f'{row["dlLow"]:g}, {ul}, {hi}, BandMode.{str(row["mode"]).lower()}),'
            )
        lines.append("};")
        return "\n".join(lines)

    dart = f'''// GENERATED FILE — do not edit by hand.
//
// Produced by `tool/gen_bands.py` from 3GPP TS 36.101 and TS 38.104, so the
// desktop test source and the app decode a channel the same way. Regenerate
// after updating `tool/banddata`.
//
// `first`/`last` are channel numbers (EARFCN for LTE, NR-ARFCN for NR) and
// `dlLow`/`ulLow` are the lowest frequencies of the band's blocks in MHz.

/// How a band pairs its two directions.
enum BandMode {{
  /// Separate uplink and downlink blocks.
  fdd,

  /// One block, used for both directions.
  tdd,

  /// Downlink only: no uplink exists on this band (band 29, n67…).
  sdl,
}}

/// One band's channel window and its lowest frequencies.
class BandPlan {{
  const BandPlan(
    this.first,
    this.last,
    this.dlLow,
    this.ulLow,
    this.ulHigh,
    this.mode,
  );

  final int first;
  final int last;
  final double dlLow;

  /// Lowest uplink frequency, or null on a downlink-only band.
  final double? ulLow;

  /// Highest uplink frequency, for the bands whose uplink block is narrower
  /// than the downlink one (66 and 70 on LTE, n66 on NR).
  final double? ulHigh;
  final BandMode mode;

  bool get isTdd => mode == BandMode.tdd;
  bool get isDlOnly => ulLow == null;

  /// Distance from the downlink block to the uplink one, in MHz.
  double? get uplinkOffset => ulLow == null ? null : ulLow! - dlLow;
}}

{dart_map("lteBandPlans", lte, "LTE bands (TS 36.101), by band number.")}

{dart_map("nrBandPlans", nr, "NR bands (TS 38.104), by band number.")}
'''
    DART_OUT.write_text(dart, encoding="utf-8")
    print(f"lte bands: {len(lte)}  nr bands: {len(nr)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
